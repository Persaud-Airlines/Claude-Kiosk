import { useCallback, useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { AlertTriangle, Check, CheckCheck, Clock, Repeat, ShieldCheck, Timer } from "lucide-react";
import { Empty, PageHeader, Spinner } from "../components/ui";
import { api, type Flag } from "../lib/api";
import { useAuth } from "../lib/auth";
import { formatDateTime, useLiveFeed } from "../lib/live";

const TYPE_META = {
  EXCESSIVE_FREQUENCY: { label: "Excessive sign-outs", icon: Repeat },
  EXTENDED_DURATION: { label: "Out too long", icon: Timer },
  UNRETURNED_SESSION: { label: "Never returned", icon: AlertTriangle },
} as const;

export default function FlagsPage() {
  const { schoolId } = useAuth();
  const [status, setStatus] = useState("OPEN");
  const [flags, setFlags] = useState<Flag[] | null>(null);
  const load = useCallback(async () => {
    if (!schoolId) return;
    const s = status === "ALL" ? "&include_suppressed=true" : `&status=${status}`;
    setFlags(await api<Flag[]>(`/api/v1/flags?school_id=${schoolId}${s}`));
  }, [schoolId, status]);
  useEffect(() => {
    load().catch(() => undefined);
  }, [load]);
  useLiveFeed(schoolId, (m) => m.type === "flag" && load(), () => load().catch(() => undefined), 15000);

  return (
    <>
      <PageHeader title="Flags" subtitle="Generated by the school's sign-out thresholds. Approved accommodations suppress matching flags automatically." />
      <div className="mb-4 flex flex-wrap gap-2">
        {["OPEN", "ACKNOWLEDGED", "RESOLVED", "SUPPRESSED_BY_EXEMPTION", "ALL"].map((s) => (
          <button key={s} onClick={() => setStatus(s)} className={`badge px-3 py-1.5 ${status === s ? "bg-navy-800 text-white" : "bg-white text-slate-600 ring-1 ring-slate-200"}`}>{s.replace(/_/g, " ").toLowerCase()}</button>
        ))}
      </div>
      <div className="card">
        {!flags ? <Spinner /> : flags.length === 0 ? <Empty title="No flags here" icon={<CheckCheck className="h-8 w-8 text-emerald-400" />} /> : (
          <ul className="divide-y divide-slate-100">{flags.map((f) => <FlagRow key={f.id} f={f} onChanged={load} />)}</ul>
        )}
      </div>
    </>
  );
}

export function FlagRow({ f, onChanged, hideName }: { f: Flag; onChanged: () => void; hideName?: boolean }) {
  const { school } = useAuth();
  const meta = TYPE_META[f.flag_type];
  const set = async (status: string) => {
    await api(`/api/v1/flags/${f.id}`, { method: "PATCH", json: { status } });
    onChanged();
  };
  return (
    <li className="flex flex-wrap items-center gap-3 px-4 py-3">
      <meta.icon className={`h-5 w-5 ${f.is_suppressed_by_exemption ? "text-emerald-500" : "text-red-500"}`} />
      <div className="min-w-0 flex-1">
        {!hideName && <Link to={`/students/${f.student_id}`} className="font-semibold text-slate-900 hover:underline">{f.student_name}</Link>}
        <div className="text-sm text-slate-700">{meta.label}: {f.trigger_details}</div>
        <div className="flex items-center gap-2 text-xs text-slate-400">
          <Clock className="h-3 w-3" /> {formatDateTime(f.created_at, school?.timezone)}
          {f.is_suppressed_by_exemption && <span className="badge bg-emerald-50 text-emerald-700"><ShieldCheck className="h-3 w-3" /> Approved Accommodation on File</span>}
        </div>
      </div>
      <span className="badge bg-slate-100 text-slate-600">{f.status.replace(/_/g, " ").toLowerCase()}</span>
      {f.status === "OPEN" && <button className="btn-secondary py-1" onClick={() => set("ACKNOWLEDGED")}><Check className="h-4 w-4" /> Acknowledge</button>}
      {(f.status === "OPEN" || f.status === "ACKNOWLEDGED") && <button className="btn-secondary py-1" onClick={() => set("RESOLVED")}><CheckCheck className="h-4 w-4" /> Resolve</button>}
    </li>
  );
}
